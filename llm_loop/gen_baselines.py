#!/usr/bin/env python3
"""Write the baseline kernels (llm_loop/baselines/*.cpp).

Each baseline is a port of its benchmark's fhe() to the loop's kernel format
(`void fhe()`, slot count from slots()), with the same operations in the same
order, so CHEHAB generates the same code. check_baselines.py verifies that.

  python3 -m llm_loop.gen_baselines
"""
from llm_loop.tasks import BASELINES, TASKS, chebyshev_terms, coefficient_set, EPS

HEADER = "// Baseline: port of {source}. Generated by llm_loop/gen_baselines.py.\n"


def chebyshev(activation: str, degree: int) -> str:
    terms = chebyshev_terms(activation, degree)
    lo, hi = coefficient_set(activation, degree)["range"]
    lines = [HEADER.format(source="benchmarks/chebyshev_ckks/chebyshev_ckks.cpp"),
             "void fhe()", "{", '  Ciphertext x("x");', '  Plaintext alpha("alpha");', "  Ciphertext z = x * alpha;"]
    if abs(-(hi + lo) / (hi - lo)) > EPS:
        lines += ['  Plaintext beta("beta");', "  z = z + beta;"]
    lines += ['  Plaintext one("one");', f"  vector<Ciphertext> t({degree + 1});", "  t[1] = z;",
              "  Ciphertext z_square = z * z;", "  t[2] = z_square + z_square - one;"]
    if degree >= 3:
        lines += [f"  for (int k = 3; k <= {degree}; ++k)", "  {", "    Ciphertext z_t = z * t[k - 1];",
                  "    t[k] = z_t + z_t - t[k - 2];", "  }"]
    first = True
    for k in terms:
        if k == 0:
            continue
        lines.append(f'  Plaintext c{k}("c{k}");')
        lines.append(f"  {'Ciphertext result =' if first else 'result = result +'} t[{k}] * c{k};")
        first = False
    if 0 in terms:
        lines += ['  Plaintext c0("c0");', "  result = result + c0;"]
    lines += ['  result.set_output("y");', "}"]
    return "\n".join(lines) + "\n"


RELU_COMPOSITE = HEADER.format(source="benchmarks/relu_ckks/relu_ckks.cpp") + """
// Odd polynomial sum_k s<stage>c<k> t^k (k = 1, 3, ..., degree), baby-step/giant-step:
// degree d >= 5 is low(t) + t^m high(t), m the largest power of two below d.
struct OddPolynomial
{
  int stage;
  vector<Ciphertext> pow2; // pow2[j] = t^(2^j)

  OddPolynomial(const Ciphertext &t, int degree, int stage_) : stage{stage_}, pow2{t}
  {
    while ((1 << pow2.size()) < degree)
      pow2.push_back(pow2.back() * pow2.back());
  }

  Plaintext coeff(int k) const { return Plaintext("s" + to_string(stage) + "c" + to_string(k)); }

  Ciphertext eval(int offset, int degree) const
  {
    const Ciphertext &t = pow2[0];
    if (degree == 1)
      return t * coeff(offset + 1);
    if (degree == 3)
      return t * coeff(offset + 1) + (t * coeff(offset + 3)) * pow2[1];
    size_t j = 0;
    while ((2 << j) < degree)
      ++j;
    const int m = 1 << j;
    return eval(offset, m - 1) + eval(offset + m, degree - m) * pow2[j];
  }
};

void fhe()
{
  Ciphertext x("x");
  Ciphertext t = x;
  for (int stage = 1; stage <= 3; ++stage)
    t = OddPolynomial(t, 7, stage).eval(0, 7);
  Plaintext half("half");
  Ciphertext h = t + half;
  Ciphertext y = x * h;
  y.set_output("y");
}
"""

QUAD = HEADER.format(source="benchmarks/quad_ckks/quad_ckks.cpp") + """void fhe()
{
  Ciphertext x("x");
  Ciphertext y = x * x;
  y.set_output("y");
}
"""

BATCHNORM = HEADER.format(source="benchmarks/batchnorm_ckks/batchnorm_ckks.cpp") + """void fhe()
{
  Ciphertext x("x");
  Plaintext a("A");
  Plaintext b("B");
  Ciphertext y = x * a + b;
  y.set_output("y");
}
"""


def elementwise(op: str) -> str:
    operand = {"add": "x1", "mul": "x1"}.get(op, "s" if "scalar" in op else "p")
    kind = "Ciphertext" if operand == "x1" else "Plaintext"
    sign = "+" if op.startswith("add") else "*"
    return HEADER.format(source="benchmarks/elementwise_ckks/elementwise_ckks.cpp") + f"""void fhe()
{{
  Ciphertext x0("x0");
  {kind} {operand}("{operand}");
  Ciphertext y = x0 {sign} {operand};
  y.set_output("y");
}}
"""


EXTRACT = HEADER.format(source="operators::extract (benchmarks/extract_embedding_ckks)") + """void fhe()
{
  Ciphertext input("input");
  Plaintext mask("mask");
  Ciphertext output = (input * mask) << static_cast<int>(slots() / 4);
  output.set_output("output");
}
"""

EXTRACT_SPARSE = HEADER.format(source="operators::extract_sparse (benchmarks/extract_embedding_ckks)") + """void fhe()
{
  Ciphertext first("first");
  Ciphertext second("second");
  Plaintext keep_front("keep_front");
  Plaintext drop_front("drop_front");
  const vector<Ciphertext> chunks{first, second};
  const size_t n = slots();
  const size_t num_dense = n / 4;
  // 8 slots: the benchmark's extract_sparse_boundary case; more: extract_sparse.
  const size_t logical_size = n <= 8 ? n + num_dense : n + n / 2;
  const size_t output_count = (logical_size - num_dense + n - 1) / n;
  for (size_t i = 0; i < output_count; ++i)
  {
    Ciphertext output = (chunks[i] * drop_front) << static_cast<int>(num_dense);
    if (i + 1 < chunks.size())
      output = output + ((chunks[i + 1] * keep_front) << static_cast<int>(num_dense));
    output.set_output("output_" + to_string(i));
  }
}
"""

TABLE_INPUTS = """  Ciphertext indicator("indicator");
  vector<Plaintext> columns;
  for (int i = 0; i < 3; ++i)
    columns.emplace_back("table_" + to_string(i));
"""

TABLE_SUMS = """  vector<Ciphertext> sums;
  for (const Plaintext &column : columns)
  {
    // reduce_add: rotate-and-sum over all slots, log2(slots) rotations.
    Ciphertext sum = indicator * column;
    for (size_t step = slots() / 2; step > 0; step /= 2)
      sum += sum << static_cast<int>(step);
    sums.push_back(sum);
  }
"""

TABLE_MULT = HEADER.format(source="operators::table_mult (benchmarks/extract_embedding_ckks)") + """void fhe()
{
""" + TABLE_INPUTS + TABLE_SUMS + """  for (int i = 0; i < 3; ++i)
    sums[i].set_output("output_" + to_string(i));
}
"""

EMBEDDING = HEADER.format(source="operators::embedding (benchmarks/extract_embedding_ckks)") + """void fhe()
{
""" + TABLE_INPUTS + """  Plaintext first_slot("first_slot");
""" + TABLE_SUMS + """  Ciphertext output = sums[0] * first_slot;
  for (int i = 1; i < 3; ++i)
    output += (sums[i] * first_slot) >> i;
  output.set_output("output");
}
"""


def baseline_source(name: str) -> str:
    task = TASKS[name]
    if task.family == "chebyshev":
        _, activation, degree = name.split("_")
        return chebyshev(activation, int(degree[1:]))
    if task.family == "elementwise":
        return elementwise(name[len("elementwise_"):])
    return {"relu_composite": RELU_COMPOSITE, "quad": QUAD, "batchnorm1d": BATCHNORM, "batchnorm2d": BATCHNORM,
            "extract": EXTRACT, "extract_linear": EXTRACT, "extract_sparse": EXTRACT_SPARSE,
            "table_mult": TABLE_MULT, "embedding": EMBEDDING}[name]


def main() -> None:
    BASELINES.mkdir(exist_ok=True)
    for name in TASKS:
        (BASELINES / f"{name}.cpp").write_text(baseline_source(name))
    print(f"wrote {len(TASKS)} baselines to {BASELINES}")


if __name__ == "__main__":
    main()

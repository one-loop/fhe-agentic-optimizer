#!/usr/bin/env python3
"""Write the baseline kernels of the optimization tasks (agent/tasks/*.cpp).

Each baseline reproduces the DSL program of its repository benchmark. The
Chebyshev kernels are generated from the committed coefficient sets with the
same term selection as benchmarks/chebyshev_ckks/chebyshev_ckks.cpp. Run from
any directory:

  python3 agent/tasks/gen_baselines.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
COEFFS = HERE.parents[1] / "benchmarks" / "dl_operators_ckks" / "chebyshev_coeffs.json"
EPS = 1e-14  # same threshold as the benchmark

HEADER = "// Baseline generated by agent/tasks/gen_baselines.py; {what}.\n"


def coefficient_set(activation: str, degree: int) -> dict:
    for s in json.loads(COEFFS.read_text())["sets"]:
        if s["activation"] == activation and s["degree"] == degree:
            return s
    raise KeyError(f"no coefficient set for {activation} degree {degree}")


def nonzero_terms(activation: str, degree: int):
    """(k, c_k) for the terms the benchmark evaluates, c0 included when non-negligible."""
    coeffs = coefficient_set(activation, degree)["coefficients"]
    return [(k, c) for k, c in enumerate(coeffs) if abs(c) > EPS]


def chebyshev_kernel(activation: str, degree: int) -> str:
    terms = [(k, c) for k, c in nonzero_terms(activation, degree) if k >= 1]
    has_c0 = any(k == 0 for k, _ in nonzero_terms(activation, degree))
    lines = [
        HEADER.format(what=f"Chebyshev {activation} degree {degree} on [-4, 4], as in benchmarks/chebyshev_ckks"),
        "void fhe()",
        "{",
        '  Ciphertext x("x");',
        '  Plaintext alpha("alpha");',
        "  Ciphertext z = x * alpha;",
        '  Plaintext one("one");',
        f"  vector<Ciphertext> t({degree + 1});",
        "  t[1] = z;",
        "  Ciphertext z_square = z * z;",
        "  t[2] = z_square + z_square - one;",
    ]
    if degree >= 3:
        lines += [
            f"  for (int k = 3; k <= {degree}; ++k)",
            "  {",
            "    Ciphertext z_t = z * t[k - 1];",
            "    t[k] = z_t + z_t - t[k - 2];",
            "  }",
        ]
    lines += ["  Ciphertext result;", "  bool has_result = false;"]
    for k, _ in terms:
        lines += [
            f'  Plaintext c{k}("c{k}");',
            f"  Ciphertext term{k} = t[{k}] * c{k};",
            f"  result = has_result ? result + term{k} : term{k};",
            "  has_result = true;",
        ]
    if has_c0:
        lines += ['  Plaintext c0("c0");', "  result = result + c0;"]
    lines += ['  result.set_output("y");', "}", ""]
    return "\n".join(lines)


ELEMENTWISE = {
    "add": ("x0 + x1", ["x0", "x1"]),
    "add_plain": ("x0 + p", ["x0", "p"]),
    "add_scalar": ("x0 + s", ["x0", "s"]),
    "mul": ("x0 * x1", ["x0", "x1"]),
    "mul_plain": ("x0 * p", ["x0", "p"]),
    "mul_scalar": ("x0 * s", ["x0", "s"]),
}


def elementwise_kernel(op: str) -> str:
    expr, labels = ELEMENTWISE[op]
    decls = []
    for label in labels:
        decls.append(f'  Ciphertext {label}("{label}");' if label.startswith("x")
                     else f'  Plaintext {label}("{label}");')
    return "\n".join([HEADER.format(what=f"elementwise {op}, as in benchmarks/elementwise_ckks"),
                      "void fhe()", "{", *decls, f"  Ciphertext y = {expr};", '  y.set_output("y");', "}", ""])


KERNELS = {}
for activation, degree in [("gelu", 7), ("silu", 7), ("sigmoid", 7), ("elu", 7), ("selu", 7),
                           ("softplus", 7), ("mish", 7), ("hardshrink", 7), ("relu", 7),
                           ("sigmoid", 5), ("relu", 2)]:
    KERNELS[f"chebyshev_{activation}_d{degree}"] = chebyshev_kernel(activation, degree)

KERNELS["quad"] = "\n".join([
    HEADER.format(what="y = x * x, as in benchmarks/quad_ckks"),
    "void fhe()", "{", '  Ciphertext x("x");', "  Ciphertext y = x * x;", '  y.set_output("y");', "}", ""])

KERNELS["batchnorm1d"] = "\n".join([
    HEADER.format(what="y = x * A + B, as in benchmarks/batchnorm_ckks (BatchNorm1d and BatchNorm2d)"),
    "void fhe()", "{", '  Ciphertext x("x");', '  Plaintext a("A");', '  Plaintext b("B");',
    "  Ciphertext y = x * a + b;", '  y.set_output("y");', "}", ""])
KERNELS["batchnorm2d"] = KERNELS["batchnorm1d"]

for op in ELEMENTWISE:
    KERNELS[f"elementwise_{op}"] = elementwise_kernel(op)

KERNELS["extract"] = "\n".join([
    HEADER.format(what="(input * mask) << slots()/4, as in benchmarks/extract_embedding_ckks (extract)"),
    "void fhe()", "{", '  Ciphertext input("input");', '  Plaintext mask("mask");',
    "  const int offset = static_cast<int>(slots() / 4);",
    "  Ciphertext output = (input * mask) << offset;", '  output.set_output("output");', "}", ""])

KERNELS["extract_linear"] = KERNELS["extract"].replace(
    "(extract)", "(extract_linear: the mask is the projection diagonal)")

KERNELS["extract_sparse"] = "\n".join([
    HEADER.format(what="two-chunk sparse extraction, as operators::extract_sparse in src/fheco/operators/extract.cpp"),
    "void fhe()", "{",
    '  Ciphertext first("first");', '  Ciphertext second("second");',
    '  Plaintext keep_front("keep_front");', '  Plaintext drop_front("drop_front");',
    "  const int num_dense = static_cast<int>(slots() / 4);",
    "  Ciphertext shifted0 = (first * drop_front) << num_dense;",
    "  Ciphertext shifted1 = (second * drop_front) << num_dense;",
    "  Ciphertext out0 = shifted0 + ((second * keep_front) << num_dense);",
    '  out0.set_output("output_0");',
    '  shifted1.set_output("output_1");',
    "}", ""])

KERNELS["table_mult"] = "\n".join([
    HEADER.format(what="reduce_add(indicator * table_i) for 3 columns, as operators::table_mult"),
    "void fhe()", "{",
    '  Ciphertext indicator("indicator");',
    "  vector<Plaintext> columns;",
    "  for (int i = 0; i < 3; ++i)",
    '    columns.emplace_back("table_" + to_string(i));',
    "  for (size_t i = 0; i < columns.size(); ++i)",
    "  {",
    "    Ciphertext r = indicator * columns[i];",
    "    for (size_t steps = slots() >> 1; steps > 0; steps >>= 1)",
    "      r += r << static_cast<int>(steps);",
    '    r.set_output("output_" + to_string(i));',
    "  }",
    "}", ""])


def main():
    for name, text in KERNELS.items():
        (HERE / f"{name}.cpp").write_text(text)
        print(f"wrote tasks/{name}.cpp")


if __name__ == "__main__":
    main()

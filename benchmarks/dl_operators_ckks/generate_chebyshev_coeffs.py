#!/usr/bin/env python3
"""Generate Chebyshev-basis coefficients for FHE-friendly activations.

Example:
  python3 generate_chebyshev_coeffs.py --activation sigmoid --degree 5 --min -4 --max 4
  python3 generate_chebyshev_coeffs.py --emit-all .   # regenerate committed sets
"""

import argparse
import json
import math
import os
import numpy as np


def activation(name: str, x: np.ndarray) -> np.ndarray:
    if name == "sigmoid":
        return 1.0 / (1.0 + np.exp(-x))
    if name == "silu":
        return x / (1.0 + np.exp(-x))
    if name == "gelu":
        # Exact GELU via erf, vectorized without requiring scipy.
        erf = np.vectorize(math.erf)
        return 0.5 * x * (1.0 + erf(x / math.sqrt(2.0)))
    if name == "elu":
        return np.where(x > 0.0, x, np.expm1(x))
    if name == "selu":
        alpha = 1.6732632423543772
        lam = 1.0507009873554805
        return lam * np.where(x > 0.0, x, alpha * np.expm1(x))
    if name == "softplus":
        return np.logaddexp(0.0, x)
    if name == "mish":
        sp = np.logaddexp(0.0, x)
        return x * np.tanh(sp)
    if name == "hardshrink":
        lambd = 0.5
        return np.where((x >= -lambd) & (x <= lambd), 0.0, x)
    if name == "relu":
        return np.maximum(x, 0.0)
    raise ValueError(f"unsupported activation: {name}")


def fit(name: str, degree: int, lo: float, hi: float, samples: int):
    if not hi > lo:
        raise ValueError("--max must exceed --min")
    if degree < 1:
        raise ValueError("degree must be >= 1")
    x = np.linspace(lo, hi, samples, dtype=np.float64)
    z = 2.0 * (x - lo) / (hi - lo) - 1.0
    y = activation(name, x)
    coeffs = np.polynomial.chebyshev.chebfit(z, y, degree)
    approx = np.polynomial.chebyshev.chebval(z, coeffs)
    return coeffs, float(np.max(np.abs(approx - y)))


ACTIVATIONS = ["gelu", "silu", "sigmoid", "elu", "selu",
               "softplus", "mish", "hardshrink", "relu"]

# Coefficient sets written by --emit-all: (activation, degree, min, max).
# All nine activations at degree 7 on [-4, 4], plus the degree-5 Sigmoid
# set used by the encrypted end-to-end test in main.cpp and a degree-2 ReLU.
# ReLU is not smooth (kink at 0), so its Chebyshev fit converges slowly; the
# degree-2 set is the cheap low-depth option (3 levels instead of 7) common in
# HE CNN inference, at a larger approximation error. Sets are appended, never
# reordered, so existing coefficients stay byte-identical.
COEFF_SETS = [(name, 7, -4.0, 4.0) for name in ACTIVATIONS if name != "relu"] + [
    ("sigmoid", 5, -4.0, 4.0),
    ("relu", 7, -4.0, 4.0),
    ("relu", 2, -4.0, 4.0),
]


def emit_all(out_dir: str, samples: int):
    sets = []
    for name, degree, lo, hi in COEFF_SETS:
        coeffs, error = fit(name, degree, lo, hi, samples)
        sets.append({
            "activation": name,
            "degree": degree,
            "range": [lo, hi],
            "coefficients": coeffs.tolist(),
            "max_fit_error": error,
        })

    with open(os.path.join(out_dir, "chebyshev_coeffs.json"), "w") as f:
        json.dump({
            "generator": "generate_chebyshev_coeffs.py --emit-all",
            "method": "numpy.polynomial.chebyshev.chebfit least squares on a "
                      "uniform grid over [min, max] mapped to [-1, 1]",
            "samples": samples,
            "numpy_version": np.__version__,
            "max_fit_error_note": "max |poly - activation| on the fitting grid; "
                                  "not a global error bound",
            "sets": sets,
        }, f, indent=2)
        f.write("\n")

    with open(os.path.join(out_dir, "chebyshev_coeffs.hpp"), "w") as f:
        f.write("// Generated by generate_chebyshev_coeffs.py --emit-all; do not edit.\n")
        f.write(f"// Fit: chebfit least squares, {samples} uniform samples, "
                f"numpy {np.__version__}.\n")
        f.write("#pragma once\n\n#include <vector>\n\nnamespace chehab::dl {\n\n")
        f.write("struct ChebyshevCoeffSet {\n"
                "    const char* activation;\n"
                "    int degree;\n"
                "    double range_min;\n"
                "    double range_max;\n"
                "    double max_fit_error; // on the fitting grid\n"
                "    std::vector<double> coeffs; // Chebyshev basis, NumPy order\n"
                "};\n\n")
        f.write("inline const std::vector<ChebyshevCoeffSet>& chebyshev_coeff_sets() {\n")
        f.write("    static const std::vector<ChebyshevCoeffSet> sets{\n")
        for s in sets:
            lo, hi = s["range"]
            f.write(f"        {{\"{s['activation']}\", {s['degree']}, {lo!r}, {hi!r}, "
                    f"{s['max_fit_error']:.17e},\n         {{")
            f.write(", ".join(f"{c:.17e}" for c in s["coefficients"]))
            f.write("}},\n")
        f.write("    };\n    return sets;\n}\n\n} // namespace chehab::dl\n")

    for s in sets:
        print(f"{s['activation']:<11} degree={s['degree']} range={s['range']} "
              f"max_fit_error={s['max_fit_error']:.4g}")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--activation", choices=ACTIVATIONS)
    p.add_argument("--degree", type=int, default=5)
    p.add_argument("--min", dest="lo", type=float, default=-4.0)
    p.add_argument("--max", dest="hi", type=float, default=4.0)
    p.add_argument("--samples", type=int, default=4097)
    p.add_argument("--json", action="store_true")
    p.add_argument("--emit-all", metavar="OUT_DIR",
                   help="write chebyshev_coeffs.json and chebyshev_coeffs.hpp "
                        "for every set in COEFF_SETS")
    args = p.parse_args()

    if args.emit_all:
        emit_all(args.emit_all, args.samples)
        return
    if not args.activation:
        p.error("--activation is required unless --emit-all is given")

    coeffs, error = fit(args.activation, args.degree, args.lo, args.hi, args.samples)
    if args.json:
        print(json.dumps({
            "activation": args.activation,
            "degree": args.degree,
            "range": [args.lo, args.hi],
            "coefficients": coeffs.tolist(),
            "max_fit_error": error,
        }, indent=2))
    else:
        print(f"// {args.activation}, degree={args.degree}, range=[{args.lo}, {args.hi}]")
        print("std::vector<double> coeffs{")
        for c in coeffs:
            print(f"    {c:.17e},")
        print("};")
        print(f"// max fit error on calibration grid: {error:.17e}")


if __name__ == "__main__":
    main()
